/**
 * The two scripts that run inside every box. Plain POSIX shell, because nothing else is guaranteed to
 * be in an image built from any combination of modules. `boxctl` only reads and signals what the
 * supervisor leaves in its state folder, so it needs no connection to it.
 */

/** Where a box keeps what the panel generates for it. */
export const BOX_INSTALL_DIR = "/opt/opsifier";
/** What a task exits with when its start hook failed, so a deployment can name the cause. */
export const BOX_HOOK_FAILED_EXIT = 78;
/** Longer than any hook may run, so a start in progress never looks like a failure. */
export const BOX_START_GRACE_SECONDS = 600;
/** Seconds a start hook may run before it counts as failed. */
const HOOK_LIMIT_SECONDS = 540;

export const BOX_CONTROL_PATH = `${BOX_INSTALL_DIR}/boxctl`;

export const BOX_SUPERVISOR_SCRIPT = `#!/bin/sh
# Generated by Opsifier: runs a box's start hook, then keeps its processes running.
set -u

ROOT=\${OPSIFIER_BOX_ROOT:-${BOX_INSTALL_DIR}}
STATE=\${OPSIFIER_BOX_STATE:-/run/opsifier/state}
WORKSPACE=\${OPSIFIER_BOX_WORKSPACE:-/workspace}
FIRST_DELAY=\${OPSIFIER_BOX_RESTART_DELAY:-1}
MAX_DELAY=30
HEALTHY_AFTER=60
STOP_GRACE=8
HOOK_LIMIT=\${OPSIFIER_BOX_HOOK_LIMIT:-${HOOK_LIMIT_SECONDS}}
HOOK_FAILED=${BOX_HOOK_FAILED_EXIT}

mkdir -p "$STATE"
rm -f "$STATE"/*.state "$STATE"/.ready "$STATE"/.stopping

if command -v setsid >/dev/null 2>&1; then SPAWN=setsid; else SPAWN=; fi
if command -v timeout >/dev/null 2>&1; then LIMIT="timeout -s TERM $HOOK_LIMIT"; else LIMIT=; fi
hook_pid=

log() { printf '[opsifier] %s\\n' "$*"; }

record() { # name state pid restarts last-exit
  printf '%s\\t%s\\t%s\\t%s\\t%s\\t%s\\n' "$1" "$2" "$3" "$4" "$5" "$(date +%s)" >"$STATE/$1.tmp" &&
    mv -f "$STATE/$1.tmp" "$STATE/$1.state"
}

# A process leads its own group, so a signal reaches whatever it started as well.
signal_process() { # signal pid
  if [ -n "$SPAWN" ]; then
    kill "-$1" -- "-$2" 2>/dev/null
  fi
  kill "-$1" "$2" 2>/dev/null
  return 0
}

print_named() { # fifo name
  awk -v tag="[$2] " '{ print tag $0; fflush() }' <"$1"
}

# Reads a process's output to its end, without waiting long for what it left behind.
drain() { # printer-pid
  (sleep 2; kill "$1" 2>/dev/null) &
  drain_timer=$!
  wait "$1" 2>/dev/null
  kill "$drain_timer" 2>/dev/null
}

run_process() { # name
  name=$1
  script=$ROOT/processes/$name
  restarts=0
  delay=$FIRST_DELAY
  last=-
  fifo=$STATE/$name.fifo
  while [ ! -e "$STATE/.stopping" ]; do
    rm -f "$fifo"
    mkfifo "$fifo" || exit 1
    print_named "$fifo" "$name" &
    printer=$!
    started=$(date +%s)
    (cd "$WORKSPACE" && exec $SPAWN /bin/sh "$script") >"$fifo" 2>&1 &
    pid=$!
    record "$name" running "$pid" "$restarts" "$last"
    wait "$pid"
    last=$?
    signal_process TERM "$pid"
    drain "$printer"
    rm -f "$fifo"
    if [ -e "$STATE/.stopping" ]; then
      break
    fi
    if [ -e "$STATE/$name.restart" ]; then
      rm -f "$STATE/$name.restart"
      log "$name is restarting, as asked"
      delay=$FIRST_DELAY
      continue
    fi
    if [ $(($(date +%s) - started)) -ge "$HEALTHY_AFTER" ]; then
      delay=$FIRST_DELAY
    fi
    restarts=$((restarts + 1))
    log "$name exited with status $last. Starting it again in $delay seconds"
    record "$name" restarting 0 "$restarts" "$last"
    waited=0
    while [ "$waited" -lt "$delay" ] && [ ! -e "$STATE/.stopping" ] && [ ! -e "$STATE/$name.restart" ]; do
      sleep 1
      waited=$((waited + 1))
    done
    rm -f "$STATE/$name.restart"
    delay=$((delay * 2))
    if [ "$delay" -gt "$MAX_DELAY" ]; then
      delay=$MAX_DELAY
    fi
  done
  record "$name" stopped 0 "$restarts" "$last"
}

anything_running() {
  for row in "$STATE"/*.state; do
    [ -e "$row" ] || continue
    pid=$(cut -f3 "$row")
    if [ "$pid" -gt 0 ] && kill -0 "$pid" 2>/dev/null; then
      return 0
    fi
  done
  return 1
}

each_pid() { # signal
  for row in "$STATE"/*.state; do
    [ -e "$row" ] || continue
    pid=$(cut -f3 "$row")
    if [ "$pid" -gt 0 ]; then
      signal_process "$1" "$pid"
    fi
  done
}

stop_all() {
  : >"$STATE/.stopping"
  if [ -n "$hook_pid" ]; then
    signal_process TERM "$hook_pid"
  fi
  each_pid TERM
  left=$STOP_GRACE
  while [ "$left" -gt 0 ] && anything_running; do
    sleep 1
    left=$((left - 1))
  done
  each_pid KILL
  exit 0
}

run_start_hook() {
  hook=$ROOT/hooks/start
  if [ ! -s "$hook" ]; then
    return 0
  fi
  log "Running the start hook"
  fifo=$STATE/start.fifo
  rm -f "$fifo"
  mkfifo "$fifo" || exit 1
  print_named "$fifo" start &
  printer=$!
  (cd "$WORKSPACE" && exec $LIMIT /bin/sh "$hook") >"$fifo" 2>&1 &
  hook_pid=$!
  wait "$hook_pid"
  code=$?
  hook_pid=
  drain "$printer"
  rm -f "$fifo"
  if [ "$code" -ne 0 ]; then
    log "The start hook failed with exit code $code, so nothing else was started"
    exit "$HOOK_FAILED"
  fi
}

trap stop_all TERM INT

run_start_hook
: >"$STATE/.ready"

for script in "$ROOT"/processes/*; do
  [ -f "$script" ] || continue
  run_process "$(basename "$script")" &
done

while :; do
  sleep 3600 &
  wait "$!"
done
`;

export const BOX_CONTROL_SCRIPT = `#!/bin/sh
# Generated by Opsifier: what the panel uses to read and steer a box's supervisor.
set -u
STATE=\${OPSIFIER_BOX_STATE:-/run/opsifier/state}

case "\${1:-}" in
status)
  for row in "$STATE"/*.state; do
    if [ -e "$row" ]; then
      cat "$row"
    fi
  done
  echo opsifier-ok
  ;;
ready)
  [ -e "$STATE/.ready" ]
  ;;
restart)
  name=\${2:-}
  row=$STATE/$name.state
  if [ -z "$name" ] || [ ! -e "$row" ]; then
    echo "No such process: $name" >&2
    exit 64
  fi
  : >"$STATE/$name.restart"
  pid=$(cut -f3 "$row")
  if [ "$pid" -gt 0 ]; then
    kill -TERM -- "-$pid" 2>/dev/null || kill -TERM "$pid" 2>/dev/null
    waited=0
    while [ "$waited" -lt 10 ] && [ "$(cut -f3 "$row")" = "$pid" ]; do
      sleep 1
      waited=$((waited + 1))
    done
    if [ "$(cut -f3 "$row")" = "$pid" ]; then
      kill -KILL -- "-$pid" 2>/dev/null || kill -KILL "$pid" 2>/dev/null
    fi
  fi
  echo opsifier-ok
  ;;
*)
  echo "Usage: boxctl status | ready | restart <name>" >&2
  exit 64
  ;;
esac
`;
